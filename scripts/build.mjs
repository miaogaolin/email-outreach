/**
 * Build a single CommonJS bundle (main.js) using the TypeScript compiler API.
 *
 * Why not esbuild? The development sandbox blocks spawning child processes, and
 * both esbuild and esbuild-wasm spawn a helper process in Node. Compiling in
 * process and wrapping the modules in a tiny CJS registry avoids that entirely
 * and still produces one loadable main.js.
 */
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const root = process.cwd();
const srcDir = path.join(root, "src");
const entry = path.join(srcDir, "obsidian", "main.ts");
const outFile = path.join(root, "main.js");

function listTsFiles(dir) {
	const out = [];
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) out.push(...listTsFiles(full));
		else if (entry.isFile() && full.endsWith(".ts") && !full.endsWith(".d.ts")) {
			out.push(full);
		}
	}
	return out;
}

const files = listTsFiles(srcDir).sort();
const idOf = (file) => path.relative(root, file).replace(/\\/g, "/");

const transpileOptions = {
	module: ts.ModuleKind.CommonJS,
	target: ts.ScriptTarget.ES2018,
	esModuleInterop: true,
	isolatedModules: true,
	importHelpers: false,
	removeComments: false,
	sourceMap: false,
};

const errors = [];
const modules = new Map();

for (const file of files) {
	const source = fs.readFileSync(file, "utf8");
	const result = ts.transpileModule(source, {
		fileName: file,
		compilerOptions: transpileOptions,
		reportDiagnostics: true,
	});
	for (const diagnostic of result.diagnostics ?? []) {
		if (diagnostic.category !== ts.DiagnosticCategory.Error) continue;
		errors.push(
			ts.formatDiagnosticsWithColorAndContext([diagnostic], {
				getCanonicalFileName: (name) => name,
				getCurrentDirectory: () => root,
				getNewLine: () => "\n",
			}),
		);
	}
	modules.set(file, result.outputText);
}

if (!modules.has(entry)) {
	console.error(`entry not found: ${entry}`);
	process.exit(1);
}

function resolveSpecifier(spec, fromFile) {
	if (!spec.startsWith(".")) return spec;
	const base = path.resolve(path.dirname(fromFile), spec);
	const candidates = [`${base}.ts`, path.join(base, "index.ts"), base];
	for (const candidate of candidates) {
		if (modules.has(candidate)) return idOf(candidate);
	}
	throw new Error(`cannot resolve ${spec} from ${idOf(fromFile)}`);
}

const chunks = [];
chunks.push(`/*
GENERATED by scripts/build.mjs from src/. Do not edit main.js directly.
*/`);
chunks.push(`"use strict";`);
chunks.push(`var __modules = Object.create(null);`);
chunks.push(`var __cache = Object.create(null);`);
chunks.push(`function __require(id) {`);
chunks.push(`  var cached = __cache[id];`);
chunks.push(`  if (cached) return cached.exports;`);
chunks.push(`  var definition = __modules[id];`);
chunks.push(`  if (!definition) return require(id);`);
chunks.push(`  var module = { exports: {} };`);
chunks.push(`  __cache[id] = module;`);
chunks.push(`  definition(module, module.exports, __require);`);
chunks.push(`  return module.exports;`);
chunks.push(`}`);
chunks.push(`__modules[${JSON.stringify(idOf(entry))}] = function(module, exports, require) {`);
chunks.push(rewriteRequires(modules.get(entry), entry));
chunks.push(`};`);

for (const [file, code] of modules) {
	if (file === entry) continue;
	chunks.push(
		`__modules[${JSON.stringify(idOf(file))}] = function(module, exports, require) {`,
	);
	chunks.push(rewriteRequires(code, file));
	chunks.push(`};`);
}

chunks.push(`var __entry = __require(${JSON.stringify(idOf(entry))});`);
chunks.push(`var __pluginClass = __entry && __entry.default ? __entry.default : __entry;`);
chunks.push(`module.exports = __pluginClass;`);
chunks.push(`module.exports.default = __pluginClass;`);

function rewriteRequires(code, file) {
	return code.replace(
		/require\((["'])([^"']+)\1\)/g,
		(match, _quote, spec) => {
			if (!spec.startsWith(".")) return match;
			const resolved = resolveSpecifier(spec, file);
			return `require(${JSON.stringify(resolved)})`;
		},
	);
}

if (errors.length > 0) {
	console.error(errors.join("\n"));
	process.exit(1);
}

fs.writeFileSync(outFile, `${chunks.join("\n")}\n`, "utf8");
const size = fs.statSync(outFile).size;
console.log(`built main.js (${modules.size} modules, ${(size / 1024).toFixed(1)} KB)`);
